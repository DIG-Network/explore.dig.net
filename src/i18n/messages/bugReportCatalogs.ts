// Per-locale translations for the shared `<BugReportButton>` widget (issue #1825).
//
// These live in ONE map keyed by locale code — deliberately NOT one file per locale like the app
// catalog. The widget owns a fixed, self-contained set of 46 keys in the `bugReport.*` namespace
// (§the bugReport.ts header); collecting all locales in a single map keeps that whole namespace
// readable in one place and mirrors the app catalog's Partial<...>-per-locale shape without
// scattering 13 tiny files. Each catalog is a Partial: any missing key falls back to the English
// base (bugReportBaseMessages), so a locale is always fully rendered.
//
// Brand/scheme literals ($DIG, XCH, DIG Network, chia://, dig://, "DIG") stay verbatim. The widget
// English strings carry no ICU placeholders, so there is nothing to preserve beyond the quoted
// "Capture screen" button reference, which each locale keeps consistent with its own button label.

import type { BugReportMessageKey } from "./bugReport";

